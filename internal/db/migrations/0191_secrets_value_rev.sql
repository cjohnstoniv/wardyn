-- value_rev is the revision a guarded Put or Delete compares (secretstore.Revisioned): a fresh number on
-- every write of a row's VALUE, and unchanged by the maintenance modes that only re-wrap or move it
-- (-rewrap, -rewrap-principal-keys, -migrate-secrets, the v0 conversion), so a renewal racing one of
-- them no longer reads as superseded. An identity column, as runner_pending_actions.queue_seq (0150):
-- an insert and `SET value_rev = DEFAULT` take the next number with no grant on a sequence, which a
-- split-role install's app role does not hold. Existing rows are numbered when the column is added.
ALTER TABLE secrets ADD COLUMN IF NOT EXISTS value_rev BIGINT GENERATED BY DEFAULT AS IDENTITY;
