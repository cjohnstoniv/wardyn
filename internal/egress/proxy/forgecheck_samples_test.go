// The samples the forge check corpus is built from. Each sample names the
// capability it is declared to classify to as a string literal, never a
// package constant, so a capability a later change retires cannot stop this
// file compiling. Azure DevOps rows come from adoscope's own golden tables,
// GitHub rows from ghscope's classifier tests.

const (
	forgeADO = "ado"
	forgeGH  = "github"

	forgeADOHost = "dev.azure.com"
	forgePR      = "/acme/proj/_apis/git/repositories/r1/pullrequests/7"
	forgeADORepo = "/acme/proj/_apis/git/repositories/r1/"
)

// adoSample is a sample against the organisation "acme".
func adoSample(name, capability, method, host, path, query, body string) forgeSample {
	return forgeSample{Name: name, Capability: capability, Request: forgeRequest{
		Method: method, Host: host, Path: path, Query: query, Body: body,
	}}
}

// ghSample is a sample against GitHub's REST API, written "METHOD /path".
func ghSample(capability, line string) forgeSample {
	method, path, _ := strings.Cut(line, " ")
	return forgeSample{Name: line, Capability: capability, Request: forgeRequest{Method: method, Path: path}}
}

// withHeader is s with one request header added (the key spelled as given).
func (s forgeSample) withHeader(k string, v ...string) forgeSample {
	for _, one := range v {
		s.Request.Header = append(s.Request.Header, [2]string{k, one})
	}
	return s
}

// called is s under another name, for a row that differs from another by a header or a body.
func (s forgeSample) called(name string) forgeSample {
	s.Name = name
	return s
}

// named turns s into a named row, one that is not a capability: it carries no
// declared capability and runs under one grant class and one rule or pin class.
func (s forgeSample) named(grant, dim string) forgeSample {
	s.Capability, s.Grant, s.Dim = "", grant, dim
	return s
}

// inOrg is s judged under another organisation pin.
func (s forgeSample) inOrg(org string) forgeSample {
	s.Org = org
	return s
}

// withPad is s with its body padded by n spaces, or declared n bytes long.
func (s forgeSample) withPad(n int) forgeSample {
	s.Request.BodyPad = n
	return s
}

func (s forgeSample) declaredLength(n int64) forgeSample {
	s.Request.DeclaredLength = n
	return s
}

